"""One-format SVG to PNG/JPEG rasterization in a short-lived subprocess.

Cairo/FreeType/Pillow can retain large native allocations even after Python
references disappear. This isolated worker exits after ONE format, returning
its memory to the 800 MiB PromoEditor service cgroup before the next.
Sources are generated by our server; customer uploads are not SVG-parsed here.
"""
from __future__ import annotations

import io
import sys
from pathlib import Path

from PIL import Image


def render_files(svg_path: Path, png_path: Path, jpeg_path: Path) -> None:
    import cairosvg

    svg_path = Path(svg_path)
    png_path = Path(png_path)
    jpeg_path = Path(jpeg_path)
    png_path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)

    # Rasterize DIRECTLY to disk; never accumulate a full-size PNG byte string
    # plus the SVG string and a second JPEG byte string in the parent process.
    cairosvg.svg2png(url=str(svg_path), write_to=str(png_path))
    with Image.open(png_path) as rendered:
        if rendered.mode == "RGB":
            rendered.save(jpeg_path, format="JPEG", quality=90, subsampling=0)
        else:
            converted = rendered.convert("RGB")
            try:
                converted.save(jpeg_path, format="JPEG", quality=90, subsampling=0)
            finally:
                converted.close()


def main() -> int:
    if len(sys.argv) != 4:
        return 2
    try:
        render_files(*[Path(arg) for arg in sys.argv[1:]])
    except Exception as exc:
        # Never echo SVG contents, environment secrets or customer originals.
        print("AI raster worker failed: " + type(exc).__name__, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
